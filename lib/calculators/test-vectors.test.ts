import { describe, expect, it } from "vitest"
import { createHash } from "node:crypto"
import { writeFileSync } from "node:fs"
import { resolve } from "node:path"
import { calculators } from "./registry"
import { FORMULA_VERSIONS } from "./versions"
import { TEST_VECTORS } from "./test-vector-data"
import {
  VECTOR_TODAY,
  buildVectorInputs,
  canonicalJson,
  describeOutcome,
  runVectorCase,
  vectorPayload,
  withFixedEnvironment,
  type VectorEntry,
} from "./test-vectors"

const sha256 = (text: string) => createHash("sha256").update(text).digest("hex")

function buildEntry(id: string, caseInputs: Record<string, string>[]): VectorEntry {
  const def = calculators.find((c) => c.id === id)!
  const payload = vectorPayload(def, caseInputs)
  return {
    version: FORMULA_VERSIONS[id],
    cases: payload.map((p) => ({ inputs: p.inputs, display: describeOutcome(p.outcome) })),
    hash: sha256(canonicalJson(payload)),
  }
}

const DATA_FILE = resolve(process.cwd(), "lib/calculators/test-vector-data.ts")

describe("test vectors", () => {
  it("regenerates lib/calculators/test-vector-data.ts when UPDATE_TEST_VECTORS=1 (pnpm integration:snapshots)", () => {
    if (process.env.UPDATE_TEST_VECTORS !== "1") return
    const data: Record<string, VectorEntry> = {}
    for (const c of calculators) data[c.id] = buildEntry(c.id, buildVectorInputs(c))
    const header =
      "// GENERATED by `pnpm integration:snapshots` from the calculators' CURRENT behaviour. Do not edit by hand.\n" +
      "// If a calculator's behaviour changes on purpose: bump its version in versions.ts, then regenerate (see docs/integration/CHANGELOG.md).\n" +
      'import type { VectorEntry } from "./test-vectors"\n\n'
    writeFileSync(DATA_FILE, `${header}export const TEST_VECTORS: Record<string, VectorEntry> = ${JSON.stringify(data, null, 2)}\n`)
  })

  it("has vectors for every calculator and none for calculators that no longer exist", () => {
    if (process.env.UPDATE_TEST_VECTORS === "1") return
    const ids = new Set(calculators.map((c) => c.id))
    const missing = calculators.filter((c) => !TEST_VECTORS[c.id]).map((c) => c.id)
    const stale = Object.keys(TEST_VECTORS).filter((id) => !ids.has(id))
    expect(missing, `no test vectors for: ${missing.join(", ")} (run pnpm integration:snapshots)`).toEqual([])
    expect(stale, `vectors for unknown calculators: ${stale.join(", ")}`).toEqual([])
  })

  it("every calculator still produces exactly the recorded results, or its version was bumped", () => {
    if (process.env.UPDATE_TEST_VECTORS === "1") return
    const behaviourChangedWithoutBump: string[] = []
    const needsRegeneration: string[] = []
    for (const c of calculators) {
      const recorded = TEST_VECTORS[c.id]
      if (!recorded) continue
      const now = buildEntry(c.id, recorded.cases.map((k) => k.inputs))
      const sameBehaviour = now.hash === recorded.hash
      const sameVersion = FORMULA_VERSIONS[c.id] === recorded.version
      if (!sameBehaviour && sameVersion) behaviourChangedWithoutBump.push(c.id)
      else if (sameBehaviour !== sameVersion) needsRegeneration.push(c.id)
    }
    expect(
      behaviourChangedWithoutBump,
      `Behaviour of these calculators changed but their version did not. If the change is intended, bump FORMULA_VERSIONS and record it in docs/integration/CHANGELOG.md, then run pnpm integration:snapshots. If it was not intended, fix the code: ${behaviourChangedWithoutBump.join(", ")}`,
    ).toEqual([])
    expect(needsRegeneration, `Version and recorded vectors disagree for: ${needsRegeneration.join(", ")}. Run pnpm integration:snapshots.`).toEqual([])
  })

  it("the recorded display text matches what each calculator shows now", () => {
    if (process.env.UPDATE_TEST_VECTORS === "1") return
    for (const c of calculators) {
      const recorded = TEST_VECTORS[c.id]
      if (!recorded || FORMULA_VERSIONS[c.id] !== recorded.version) continue
      recorded.cases.forEach((k, i) => expect(describeOutcome(runVectorCase(c, k.inputs)), `${c.id} case ${i}`).toBe(k.display))
    }
  })
})

describe("vector helpers", () => {
  it("withFixedEnvironment fixes today's local calendar date and restores the clock", () => {
    const real = Date.now()
    const inside = withFixedEnvironment(() => {
      const d = new Date()
      return [d.getFullYear(), d.getMonth() + 1, d.getDate(), Date.now() === d.getTime()]
    })
    expect(inside).toEqual([VECTOR_TODAY.year, VECTOR_TODAY.month, VECTOR_TODAY.day, true])
    expect(Math.abs(Date.now() - real) < 60_000).toBe(true)
    expect(new Date("2026-01-02").toISOString()).toBe("2026-01-02T00:00:00.000Z")
  })

  it("withFixedEnvironment forces en-US number formatting and restores it", () => {
    const text = withFixedEnvironment(() => (1234567).toLocaleString())
    expect(text).toBe("1,234,567")
  })

  it("restores the environment even when the function throws", () => {
    expect(() => withFixedEnvironment(() => { throw new Error("x") })).toThrow()
    expect(Math.abs(Date.now() - new Date().getTime()) < 60_000).toBe(true)
  })

  it("canonicalJson ignores key order", () => {
    expect(canonicalJson({ b: 1, a: { d: 2, c: [{ y: 1, x: 2 }] } })).toBe(canonicalJson({ a: { c: [{ x: 2, y: 1 }], d: 2 }, b: 1 }))
  })

  it("every vector input set is built from the calculator's own inputs", () => {
    for (const c of calculators) {
      for (const inputs of buildVectorInputs(c)) expect(Object.keys(inputs).sort(), c.id).toEqual(c.inputs.map((i) => i.id).sort())
    }
  })
})
